//! Generated mask assets have an explicit semantic type, never inferred from
//! an ordinary imported image. Their PNG payload is 8-bit grayscale.
use super::*;
use crate::MASK_MEDIA_TYPE;
#[cfg(feature = "desktop")]
use std::sync::atomic::AtomicBool;

pub(super) fn mask_info(bytes: &[u8]) -> Result<AssetInfo, ProjectError> {
    let mut info = encoded_image_info(bytes)?;
    let geometry = image_metadata::inspect(bytes, &info)?;
    if geometry.orientation != image::metadata::Orientation::NoTransforms {
        return Err(ProjectError::Invalid(
            tr(
                "Mask 像素坐标必须已规范化，不能携带旋转或镜像方向",
                "Mask pixels must be normalized without rotation or mirror metadata",
            )
            .into(),
        ));
    }
    if info.media_type != "image/png" || bytes.get(24) != Some(&8) || bytes.get(25) != Some(&0) {
        return Err(ProjectError::Invalid(
            tr(
                "Mask 输出必须是 8 位灰度 PNG",
                "Mask output must be an 8-bit grayscale PNG",
            )
            .into(),
        ));
    }
    info.media_type = MASK_MEDIA_TYPE;
    Ok(info)
}

#[cfg(feature = "desktop")]
impl LocalProject {
    /// Store a raster generated by the mask editor. Does not change or replace
    /// its input image. Node binding is a separate host editor transaction.
    pub fn store_mask(
        &mut self,
        source: &crate::mask::MaskSource,
        raster: &crate::mask::MaskRaster,
        cancelled: &AtomicBool,
    ) -> Result<ProjectAsset, ProjectError> {
        use image::ImageEncoder;
        source
            .validate()
            .map_err(|e| ProjectError::Invalid(e.to_string()))?;
        if raster.width != source.width
            || raster.height != source.height
            || raster.pixels.len() as u64 != u64::from(source.width) * u64::from(source.height)
        {
            return Err(ProjectError::Invalid(
                tr(
                    "Mask 尺寸必须与原图一致",
                    "The mask dimensions must match the source image",
                )
                .into(),
            ));
        }
        let _transaction = transaction()?;
        self.check_revision()?;
        let (source_path, original) = self.asset_path(&source.asset_key)?;
        if !matches!(original.media_type.as_str(), "image/png" | "image/jpeg")
            || original.width != source.width
            || original.height != source.height
        {
            return Err(ProjectError::Invalid(
                tr(
                    "Mask 原图身份或尺寸已变更",
                    "The mask source image or dimensions changed",
                )
                .into(),
            ));
        }
        verify_asset(&source_path, original)?;
        if self.project.assets.len() >= MAX_PROJECT_ASSETS {
            return Err(ProjectError::TooLarge(
                tr(
                    "项目素材数量已达上限（512）",
                    "project has reached its 512 asset limit",
                )
                .into(),
            ));
        }
        let mut encoded = BoundedMaskBytes(Vec::new(), cancelled);
        image::codecs::png::PngEncoder::new(&mut encoded)
            .write_image(
                &raster.pixels,
                raster.width,
                raster.height,
                image::ExtendedColorType::L8,
            )
            .map_err(|e| ProjectError::Invalid(e.to_string()))?;
        let bytes = encoded.0;
        if cancelled.load(Ordering::Acquire) {
            return Err(ProjectError::Invalid(
                tr("遮罩应用已取消", "Applying the mask was canceled").into(),
            ));
        }
        let info = mask_info(&bytes)?;
        let total = self.project.assets.iter().map(|a| a.byte_len).sum::<u64>();
        if total.saturating_add(bytes.len() as u64) > MAX_PROJECT_ASSET_BYTES {
            return Err(ProjectError::TooLarge(
                tr(
                    "项目素材总大小超过 512 MiB",
                    "project assets exceed 512 MiB",
                )
                .into(),
            ));
        }
        let asset = ProjectAsset {
            key: format!("assets/{}.png", unique_name("mask")),
            name: tr_format!(
                "遮罩 {}×{}.png",
                "Mask {}×{}.png",
                source.width,
                source.height
            ),
            media_type: MASK_MEDIA_TYPE.into(),
            byte_len: bytes.len() as u64,
            width: info.width,
            height: info.height,
        };
        checked_directory(&self.directory.join("assets"), false)?;
        let path = self.directory.join(&asset.key);
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)?;
        let result = (|| {
            file.write_all(&bytes)?;
            file.sync_all()?;
            drop(file);
            #[cfg(unix)]
            File::open(self.directory.join("assets"))?.sync_all()?;
            let mut candidate = self.next_revision()?;
            candidate.assets.push(asset.clone());
            if cancelled.load(Ordering::Acquire) {
                return Err(ProjectError::Invalid(
                    tr("遮罩应用已取消", "Applying the mask was canceled").into(),
                ));
            }
            write_project(&self.directory, &candidate)?;
            self.project = candidate;
            Ok(asset)
        })();
        if result.is_err() {
            let _ = fs::remove_file(path);
        }
        result
    }
}

#[cfg(feature = "desktop")]
struct BoundedMaskBytes<'a>(Vec<u8>, &'a AtomicBool);
#[cfg(feature = "desktop")]
impl Write for BoundedMaskBytes<'_> {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        if self.1.load(Ordering::Acquire) {
            return Err(io::Error::other(tr(
                "遮罩应用已取消",
                "Applying the mask was canceled",
            )));
        }
        if self.0.len().saturating_add(bytes.len()) as u64 > MAX_IMAGE_BYTES {
            return Err(io::Error::other(tr(
                "遮罩 PNG 超过 32 MiB",
                "Mask PNG exceeds 32 MiB",
            )));
        }
        self.0
            .try_reserve_exact(bytes.len())
            .map_err(io::Error::other)?;
        self.0.extend_from_slice(bytes);
        Ok(bytes.len())
    }
    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

#[cfg(all(test, feature = "desktop"))]
mod tests {
    use super::*;
    use crate::mask::{MaskRaster, MaskSource};
    use image::ImageEncoder;
    #[test]
    fn mask_png_is_typed_grayscale_same_size_and_preserves_its_source() {
        let root = std::env::temp_dir().join(unique_name("flow-mask-test"));
        fs::create_dir(&root).unwrap();
        let source_path = root.join("source.png");
        let mut source_png = Vec::new();
        image::codecs::png::PngEncoder::new(&mut source_png)
            .write_image(&[90; 18], 2, 3, image::ExtendedColorType::Rgb8)
            .unwrap();
        fs::write(&source_path, &source_png).unwrap();
        let registry = crate::standard_registry();
        let store = ProjectStore::new(root.join("projects")).unwrap();
        let mut project = store
            .create_project("Mask test", &FlowDocument::default(), &registry)
            .unwrap();
        let original = project.import_image(&source_path).unwrap();
        let source = MaskSource::new(&original.key, 2, 3).unwrap();
        let raster = MaskRaster {
            width: 2,
            height: 3,
            pixels: vec![0, 255, 255, 0, 0, 255],
        };
        let output = project
            .store_mask(&source, &raster, &AtomicBool::new(false))
            .unwrap();
        assert_eq!(output.media_type, MASK_MEDIA_TYPE);
        assert_eq!((output.width, output.height), (2, 3));
        let bytes = fs::read(project.resolve_asset(&output.key).unwrap()).unwrap();
        assert_eq!(bytes[24], 8);
        assert_eq!(bytes[25], 0);
        let decoded = image::load_from_memory(&bytes).unwrap().into_luma8();
        assert_eq!(decoded.as_raw(), &raster.pixels);
        assert_eq!(
            fs::read(project.resolve_asset(&original.key).unwrap()).unwrap(),
            source_png
        );
        let before = fs::read(project.directory.join(PROJECT_FILE)).unwrap();
        let count = project.assets().len();
        assert!(
            project
                .store_mask(&source, &raster, &AtomicBool::new(true))
                .is_err()
        );
        assert_eq!(project.assets().len(), count);
        assert_eq!(
            fs::read(project.directory.join(PROJECT_FILE)).unwrap(),
            before
        );
        assert!(
            mask_info(&source_png).is_err(),
            "ordinary RGB PNG is not a Mask"
        );
        fs::remove_dir_all(root).unwrap();
    }
}
