//! Pure custom sizing hooks; asynchronous work belongs to resource producers.
use crate::{ChangeOrigin, ElementHandle, EngineError, PropertyKey, SceneEngine};
use gpui_flow_scene::{Affine, Bounds, Point, Shape, Size};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum CustomResizePolicy {
    #[default]
    Disabled,
    Dimensions,
    Uniform,
}

/// The same local bounds used by geometry and picking, plus intrinsic limits.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct CustomMeasurement {
    pub bounds: Bounds,
    pub minimum: Size,
    pub maximum: Size,
}
impl CustomMeasurement {
    pub(crate) fn validate(self, bounds: Bounds) -> Result<(), EngineError> {
        if self.bounds != bounds
            || !self.bounds.size.is_positive()
            || !self.minimum.is_positive()
            || !self.maximum.is_positive()
            || self.maximum.width > 1_000_000.
            || self.maximum.height > 1_000_000.
            || self.minimum.width > self.bounds.size.width
            || self.minimum.height > self.bounds.size.height
            || self.maximum.width < self.bounds.size.width
            || self.maximum.height < self.bounds.size.height
        {
            return Err(EngineError::Registry(
                "invalid custom measurement or geometry disagreement".into(),
            ));
        }
        Ok(())
    }
}

/// Apply both fields in one ordinary editor transaction/session, never separately.
#[derive(Clone, Debug, PartialEq)]
pub struct CustomResizePatch {
    pub shape: Shape,
    pub transform: Affine,
}
impl SceneEngine {
    pub fn measure_custom(&self, handle: ElementHandle) -> Result<CustomMeasurement, EngineError> {
        self.attached_id(handle)?;
        let object = self.object(handle)?;
        let Shape::Custom(custom) = &object.shape else {
            return Err(EngineError::Registry("target is not Custom".into()));
        };
        self.registry().measure_custom(custom)
    }

    /// Keep a normalized local anchor fixed in parent space. Geometry/data are
    /// regenerated by the registered definition; affine linear terms stay exact.
    /// A derived layout that overrides either requested field rejects the edit.
    pub fn preview_custom_resize(
        &self,
        handle: ElementHandle,
        size: Size,
        anchor: Point,
    ) -> Result<CustomResizePatch, EngineError> {
        self.attached_id(handle)?;
        if !size.is_positive()
            || !anchor.x.is_finite()
            || !anchor.y.is_finite()
            || !(0. ..=1.).contains(&anchor.x)
            || !(0. ..=1.).contains(&anchor.y)
        {
            return Err(EngineError::Property(
                "invalid custom resize size or anchor".into(),
            ));
        }
        let object = self.object(handle)?;
        let Shape::Custom(custom) = &object.shape else {
            return Err(EngineError::Registry("target is not Custom".into()));
        };
        let measured = self.measure_custom(handle)?;
        let shape = self.registry().resize_custom(custom, size)?;
        let Shape::Custom(resized) = &shape else {
            unreachable!("registry preserves Custom")
        };
        let at = |b: Bounds| {
            Point::new(
                b.origin.x + b.size.width * anchor.x,
                b.origin.y + b.size.height * anchor.y,
            )
        };
        let old = at(measured.bounds);
        let new = at(resized.bounds);
        let transform = object.transform * Affine::translation(old.x - new.x, old.y - new.y);
        if transform.inverse().is_none() {
            return Err(EngineError::Property(
                "custom resize has a singular transform".into(),
            ));
        }
        let candidate = self.preview_properties_batch_with_origin(
            ChangeOrigin::Edit,
            [
                (
                    handle,
                    PropertyKey::Shape,
                    serde_json::to_value(&shape)
                        .map_err(|e| EngineError::Property(e.to_string()))?,
                ),
                (
                    handle,
                    PropertyKey::Transform,
                    serde_json::to_value(transform)
                        .map_err(|e| EngineError::Property(e.to_string()))?,
                ),
            ],
        )?;
        let actual = &candidate.get(&object.id).expect("attached target").object;
        let parent_world = self
            .scene()
            .get(&object.id)
            .expect("attached target")
            .parent
            .as_ref()
            .map(|parent| self.scene().world_transform(parent))
            .transpose()?
            .unwrap_or(Affine::IDENTITY);
        if actual.shape != shape
            || actual.transform != transform
            || candidate.world_transform(&object.id)? != parent_world * transform
        {
            return Err(EngineError::Layout(
                "custom resize conflicts with layout ownership".into(),
            ));
        }
        Ok(CustomResizePatch { shape, transform })
    }
}
